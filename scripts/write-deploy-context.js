// Netlify's build CONTEXT is not guaranteed in the function runtime. Bake only
// this non-secret flag into the function bundle; never bake database credentials.
const fs = require('node:fs');
const path = require('node:path');
const context = process.env.CONTEXT;
const preview = context === 'deploy-preview' || context === 'branch-deploy' ||
  (process.env.NETLIFY === 'true' && context !== 'production');
fs.writeFileSync(path.join(__dirname, '../netlify/functions/lib/deploymentContext.ts'),
  `// Generated by scripts/write-deploy-context.js. No secrets.\nexport const PREVIEW_BUILD: boolean = ${preview};\n`);
console.log(`Function persistence context: ${preview ? 'isolated preview required' : 'production/local'}`);
